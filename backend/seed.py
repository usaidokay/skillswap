def seed(conn):
    if conn.execute("SELECT COUNT(*) FROM users WHERE is_demo = 1").fetchone()[0]:
        return 0
    with db.tx(conn):
        for name, city, mode, times, rating, swaps, ok, bio, teach, learn in USERS:
            uid = conn.execute(
                "INSERT INTO users (name, city, mode, times, bio, verified, is_demo, rating, swaps_done) VALUES (?,?,?,?,?,?,1,?,?)",
                (name, city, mode, times, bio, ok, rating, swaps)).lastrowid
            for s, lv, d in teach:
                conn.execute("INSERT INTO skills (user_id, kind, name, category, level, detail) VALUES (?,?,?,?,?,?)",
                             (uid, "teach", s, cat_of(s), lv, d))
            for s in learn:
                conn.execute("INSERT INTO skills (user_id, kind, name, category) VALUES (?,?,?,?)",
                             (uid, "learn", s, cat_of(s)))
    return len(USERS)


